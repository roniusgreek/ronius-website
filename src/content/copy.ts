type EventContentBlock = { type: "p"; text: string } | { type: "list"; items: string[] };
type EventSection = { heading: string; blocks: EventContentBlock[] };
type EventCategory = {
  id: string;
  title: string;
  heading: string;
  intro?: string[];
  sections: EventSection[];
  cta: string;
  video: { src: string; poster: string };
};

function p(text: string): EventContentBlock {
  return { type: "p", text };
}

